export interface CalendarDay {
  date: Date;
  iso: string;
  dayNum: number;
  thaiDay: ThaiDay;
  profile: DayProfile;
  isToday: boolean;
  isHoliday: boolean;
  holidayName?: string;
  isWanPhra: boolean;
  isWanKhon: boolean;
  isCurrentMonth: boolean;
}

export function buildCalendar(year: number, month: number, todayIso: string): CalendarDay[] {
  const firstDay = new Date(year, month, 1);
  const lastDay = new Date(year, month + 1, 0);

  // pad start to Sunday
  const startPad = firstDay.getDay();
  // pad end to Saturday
  const endPad = 6 - lastDay.getDay();

  const days: CalendarDay[] = [];

  for (let i = -startPad; i <= lastDay.getDate() - 1 + endPad; i++) {
    const date = new Date(year, month, 1 + i);
    const iso = toISODate(date);
    const thaiDay = getThaiDay(date);
    days.push({
      date,
      iso,
      dayNum: date.getDate(),
      thaiDay,
      profile: DAY_PROFILES[thaiDay],
      isToday: iso === todayIso,
      isHoliday: iso in THAI_HOLIDAYS,
      holidayName: THAI_HOLIDAYS[iso],
      isWanPhra: WAN_PHRA_DATES.has(iso),
      isWanKhon: WAN_KHON_DATES.has(iso),
      isCurrentMonth: date.getMonth() === month,
    });
  }
  return days;
}

// ─── Helpers: parse ?m=YYYY-MM param ─────────────────────────────────────────

export function parseMonthParam(m: string | undefined): { year: number; month: number } {
  if (isValidMonthParam(m)) {
    const [y, mo] = m.split('-').map(Number);
    return { year: y, month: mo - 1 };
  }
  const now = getBangkokNow();
  return { year: now.getFullYear(), month: now.getMonth() };
}
