// วันโกน = day before each วันพระ (derivedno need for a separate static set)
function buildWanKhonSet(): Set<string> {
  const result = new Set<string>();
  for (const iso of WAN_PHRA_DATES) {
    const d = new Date(iso);
    d.setDate(d.getDate() - 1);
    result.add(`${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`);
  }
  return result;
}
export const WAN_KHON_DATES = buildWanKhonSet();

// ─── Helpers ─────────────────────────────────────────────────────────────────

export function toISODate(date: Date): string {
  return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}-${String(date.getDate()).padStart(2, '0')}`;
}

export function getBangkokNow(): Date {
  return new Date(new Date().toLocaleString('en-US', { timeZone: 'Asia/Bangkok' }));
}

